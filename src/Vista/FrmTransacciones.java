    public void cargarHistorial(List<Transaccion> historial) {
        DefaultTableModel model = (DefaultTableModel) tblHistorial.getModel();
        model.setRowCount(0); 
        for (Transaccion t : historial) {
            model.addRow(new Object[]{
                t.getFecha(),
                t.getTipotransaccion(),
                t.getMonto(),
                t.getCuentaOrigen(),
                t.getCuentaDestino(),
                t.getSaldoFinal()
            });
        }
    }


